#!/usr/bin/env python3
# generate-demo-media.py - Agora - unit 003, wave 11, task T-1101.
#
# Writes every non-YAML file this package ships under content/file/ - the 34
# demonstration PDFs and the 5 CSV distributions - and is the source of truth
# named by the `source URL` column of content/MEDIA-LICENCES.md.
#
# -----------------------------------------------------------------------------
# WHY IT EXISTS (D-042, signed A by [andres] 2026-08-27)
# -----------------------------------------------------------------------------
# All 39 rows of content/MEDIA-LICENCES.md gave their source as "generated by
# the template's own build script", and NO SUCH SCRIPT WAS IN THE REPOSITORY.
# The manifest's own header says the column exists so that "the claim can be
# re-checked by someone else"; a provenance claim pointing at an unversioned
# artefact is the one failure that file was written to prevent, committed by
# the file itself. It is also the exact question Drupal.org's third-party asset
# policy asks - who authored it, and where did you get it from - so it is a
# marketplace matter and not a tidiness one.
#
# /tests is export-ignore'd (see .gitattributes), so this file lands in the
# repository, where a reviewer can re-run it, and NOT in the packaged tarball.
# The packaging cost is therefore zero, and that is the fact that decided the
# option.
#
# -----------------------------------------------------------------------------
# THE DATA SOURCE, AND WHAT IS AND IS NOT DERIVED
# -----------------------------------------------------------------------------
# The 34 PDFs are DERIVED. Nothing in them is typed here: every string is read
# out of content/node/*.yml and the entities those nodes depend on.
#
#   agora_base_document -> title, the council name, the document type term, the
#                          responsible area term, the financial year term and
#                          the summary field. The file it is written to is
#                          resolved node -> media -> file, so a PDF whose media
#                          entity was repointed is regenerated under its new
#                          name rather than silently left behind.
#   agora_base_person   -> the person's name, post, area term, remuneration and
#                          severance. The file is resolved node -> file
#                          directly: a declaration hangs off the person node's
#                          own file field, with no media entity in between.
#
# The 5 CSV distributions are NOT derivable and are held here as literal text,
# which is stated rather than implied. Their figures - budget execution by
# chapter, a street tree inventory - are invented data that exists nowhere else
# in the package, so "generated" means this script emits the exact bytes, not
# that it computes them. Two of them (contracts, grants) COULD be derived from
# the corresponding nodes; they are not, because deriving two of five would make
# the file's provenance non-uniform for no gain, and the manifest's claim is
# about who wrote the bytes rather than about how clever the writer was.
#
# -----------------------------------------------------------------------------
# PYTHON STANDARD LIBRARY ONLY. THIS IS NOT A PREFERENCE.
# -----------------------------------------------------------------------------
# PyYAML is installed on the development host and is NOT in the CI image, and
# this project has already had one invariant nearly ship green because its
# parser could not load. So the YAML this script reads is parsed by the reader
# below, which accepts EXACTLY the subset `drush site:export` emits and raises
# on anything else. It refuses rather than guesses: a parser that quietly
# returned nothing would make every count here zero and every comparison
# vacuously true, which is I-028's shape.
#
# "Raises on anything else" was FALSIFIED before it was written down, against
# seven shapes: a flow mapping, a flow sequence, an anchor, an alias, a block
# scalar, a tab indent and a CRLF file. The first three were ACCEPTED on the
# first pass - returned as bare strings, which is the silent mis-parse this
# whole paragraph exists to rule out - and the guard in `_scalar()` is what
# closed them. A claim of strictness that nobody tried to break is not a claim.
#
# There is no PDF library either, so the PDF bytes are written directly. That is
# evidently what produced the current files, and the structure is small enough
# to state in full: a catalog, a page tree of one A4 page, one Type1 Helvetica
# resource (one of the fourteen standard fonts a reader supplies, so no font is
# redistributed), one uncompressed content stream of `BT ... Tj ET` text
# operations, an Info dictionary, and a classic cross-reference table.
#
# -----------------------------------------------------------------------------
# NO METADATA, AND NO CLOCK
# -----------------------------------------------------------------------------
# tests/bin/no-secrets level 3 sweeps EXIF, XMP and C2PA/JUMBF across every
# binary in the package and is blocking. Nothing here writes any of them. The
# Info dictionary carries `/Producer` and `/Title` and NOTHING ELSE: no
# `/CreationDate`, no `/ModDate`, no `/ID`, no `/Author`. That is deliberate on
# two counts - a timestamp is personal-adjacent metadata, and it would also make
# the output depend on the clock, so `--check` could never be an equality test.
#
# The output is BYTE-DETERMINISTIC: the same content/ tree produces the same 39
# files on any host, any day. `--check` asserts that, and it is what makes this
# script's claim on the manifest falsifiable rather than decorative.
#
# NO CARRIAGE RETURNS ARE EVER WRITTEN. .gitattributes sets `* text=auto
# eol=lf`, and git classifies both the PDFs and the CSVs as TEXT - verified with
# `git ls-files --eol`, which reports `i/lf w/lf` for both. A CR emitted here
# would be normalised out of the working tree by git and the file on disk would
# stop matching the file this script wrote.
#
# -----------------------------------------------------------------------------
# CONTRACT
# -----------------------------------------------------------------------------
#   scope:    content/node/*.yml plus the media, file and taxonomy_term entities
#             they depend on; output under content/file/
#   scanned:  <N> node(s), and N must be > 0 or this script exits 1
#   targets:  <N> file(s) - 34 derived PDFs + 5 literal CSVs
#   findings: <M>, each printed as  path  reason
#   exit 0 iff M == 0
#
# Two modes, and the default is the safe one:
#   --check   (default) generate in memory, compare against the files on disk,
#             report every difference and its size delta. Writes nothing.
#   --write   generate and write. Prints which files changed and by how much.
#
# A zero-length scan, an unresolvable reference, a node whose bundle this script
# does not know, or a PDF target with no node behind it is a FINDING, never a
# skip: an unevaluated file is not a correct file (I-027).
#
# ⚠️ WHEN THE BYTES CHANGE, THREE OTHER PLACES CARRY THE SIZE and none of them
# is updated from here, because they are exported entity data rather than
# generated artefacts:
#   content/file/<uuid>.yml     `filesize`
#   content/media/<uuid>.yml    `description` ("..., PDF, 1,789 bytes")
#   content/MEDIA-LICENCES.md   no size, but one row per file
# `--check` prints the delta for exactly this reason. `tests/bin/media-licence`
# catches a missing row; nothing catches a stale `filesize`, so it is
# named here.
#
# Usage:
#   python3 tests/bin/generate-demo-media.py            # check, writes nothing
#   python3 tests/bin/generate-demo-media.py --write    # regenerate

# `endobj` and `startxref` are PDF WIRE SYNTAX written by build_pdf(), not
# prose. They are scoped out HERE, by name, rather than declared in
# .cspell-project-words.txt: that list is for vocabulary this project WRITES,
# and putting a file-format keyword in it would make the word acceptable in
# prose everywhere. ⚠️ A `cspell:disable`/`cspell:enable` pair around the
# function was tried first and DID NOT SUPPRESS THEM - measured, 2026-08-27,
