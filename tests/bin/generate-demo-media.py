def main(argv):
    write = '--write' in argv[1:]
    for arg in argv[1:]:
        if arg not in ('--write', '--check'):
            sys.stderr.write('unknown argument: %s\n' % arg)
            return 2

    print('')
    print('generate-demo-media.py - Agora - the source of truth for content/file/ '
          '(D-042)')
    print('repo:  %s' % REPO_ROOT)
    print('mode:  %s' % ('WRITE' if write else 'CHECK (nothing is written)'))
    print('')

    nodes = read_dir('node')
    media = read_dir('media')
    files = read_dir('file')
    terms = read_dir('taxonomy_term')

    print('scope:')
    print('  content/node/          %d entity file(s)' % len(nodes))
    print('  content/media/         %d' % len(media))
    print('  content/file/          %d' % len(files))
    print('  content/taxonomy_term/ %d' % len(terms))

    findings = []

    def term_name(uuid, why):
        entity = terms.get(uuid)
        if entity is None:
            findings.append(('content/taxonomy_term/%s' % uuid,
                             'referenced as %s and not present' % why))
            return None
        return field_value(entity, 'name')

    def file_name(uuid, why):
        entity = files.get(uuid)
        if entity is None:
            findings.append(('content/file/%s' % uuid,
                             'referenced as %s and not present' % why))
            return None
        return field_value(entity, 'filename')

    targets = {}
    documents = 0
    people = 0
    undeclared = []

    for uuid in sorted(nodes):
        node = nodes[uuid]
        bundle = (node.get('_meta') or {}).get('bundle')
        title = field_value(node, 'title')

        if bundle == 'agora_base_document':
            documents += 1
            media_uuid = field_entity(node, 'field_agora_base_document_file')
            if media_uuid is None or media_uuid not in media:
                findings.append(('content/node/%s.yml' % uuid,
                                 'document node with no resolvable media entity'))
                continue
            file_uuid = field_entity(media[media_uuid], 'field_media_document')
            name = file_name(file_uuid, 'the file of %s' % title)
            if name is None:
                continue
            doc_type = term_name(field_entity(node, 'field_agora_base_document_type'),
                                 'the document type of %s' % title)
            area = term_name(field_entity(node, 'field_agora_base_area'),
                             'the area of %s' % title)
            year = term_name(field_entity(node, 'field_agora_base_financial_year'),
                             'the financial year of %s' % title)
            summary = field_value(node, 'field_agora_base_summary') or ''
            blocks = [
                [title],
                [COUNCIL,
                 'Document type: %s' % doc_type,
                 'Responsible area: %s' % area,
                 'Financial year: %s' % year],
                wrap(summary, SUMMARY_WIDTH),
            ] + standing_blocks()
            targets[name] = build_pdf(title, blocks)

        elif bundle == 'agora_base_person':
            people += 1
            file_uuid = field_entity(node, 'field_agora_base_declaration')
            if file_uuid is None:
                # NOT a finding, and it is the corpus being right rather than a
                # gap. The declaration is headed "Register of interests of
                # elected members", and two of the eight people this template
                # ships are NOT elected: the Municipal Secretary and the
                # Municipal Treasurer are career officials appointed by
                # competitive examination. Generating a declaration for them
                # would put a document in the register that the register's own
                # heading excludes. Counted and PRINTED, so that "34 PDFs from
                # 36 records" can never quietly become "two we forgot".
                undeclared.append(title)
                continue
            name = file_name(file_uuid, 'the declaration of %s' % title)
            if name is None:
                continue
            area = term_name(field_entity(node, 'field_agora_base_area'),
                             'the area of %s' % title)
            blocks = [
                [DECLARATION_TITLE],
                [COUNCIL, DECLARATION_REGISTER],
                ['Name: %s' % title,
                 'Post: %s' % field_value(node, 'field_agora_base_position'),
                 'Area: %s' % area,
                 'Annual remuneration for the post: %s EUR'
                 % field_value(node, 'field_agora_base_remuneration'),
                 'Severance entitlement on leaving office: %s EUR'
                 % field_value(node, 'field_agora_base_severance')],
                wrap(DECLARATION_NOTE, PROSE_WIDTH),
            ] + standing_blocks()
            targets[name] = build_pdf(DECLARATION_TITLE, blocks)

    for name, text in CSV_FILES.items():
        targets[name] = text.encode('utf-8')

    pdfs = sum(1 for name in targets if name.endswith('.pdf'))
    csvs = sum(1 for name in targets if name.endswith('.csv'))
    print('')
    print('scanned:  %d node(s) - %d document(s), %d person record(s)'
          % (len(nodes), documents, people))
    print('targets:  %d file(s) - %d derived PDF(s) + %d literal CSV(s)'
          % (len(targets), pdfs, csvs))
    print('no declaration (not elected members, so the register excludes them): '
          '%d - %s' % (len(undeclared), ', '.join(undeclared) or 'none'))

    if not targets:
        print('')
        print('FAILURE: 0 targets - a run that generates nothing proves nothing '
              '(I-028).')
        return 1

    # Every media file already on disk must be a target, or this script is not
    # the source of truth it claims to be on the manifest.
    on_disk = sorted(
        name for name in os.listdir(OUT_DIR)
        if not name.endswith('.yml')
    )
    for name in on_disk:
        if name not in targets:
            findings.append(('content/file/%s' % name,
                             'shipped under content/file/ and generated by nothing '
                             'here - the manifest would name this script for a file '
                             'it does not produce'))

    changed = 0
    identical = 0
    for name in sorted(targets):
        path = os.path.join(OUT_DIR, name)
        new = targets[name]
        old = None
        if os.path.exists(path):
            with open(path, 'rb') as handle:
                old = handle.read()
        if old == new:
            identical += 1
            continue
        changed += 1
        delta = len(new) - (len(old) if old is not None else 0)
        state = 'absent' if old is None else '%d bytes' % len(old)
        print('  %-32s %s -> %d bytes (%+d)' % (name, state, len(new), delta))
        if write:
            with open(path, 'wb') as handle:
                handle.write(new)
        else:
            findings.append(('content/file/%s' % name,
                             'on disk (%s) differs from what this script generates '
                             '(%d bytes)' % (state, len(new))))

    print('')
    print('identical: %d   %s: %d' % (identical, 'written' if write else 'differing',
                                      changed))
    print('findings:  %d' % len(findings))
    for path, reason in findings:
        print('  %s  %s' % (path, reason))

    if write:
        print('')
        print('generate-demo-media.py: wrote %d file(s).' % changed)
        if changed:
            # ASCII only on stdout. This host's console is cp1252 and a
            # non-ASCII character here raises UnicodeEncodeError, which would
            # turn a successful regeneration into a traceback. Measured
            # 2026-08-27, with a warning sign in this very line.
            print('WARNING: filesize in content/file/<uuid>.yml and the byte count in')
            print('   content/media/<uuid>.yml description are NOT updated from here.')
        return 1 if findings else 0

    if findings:
        print('')
        print('generate-demo-media.py: %d finding(s).' % len(findings))
        return 1
    print('')
    print('generate-demo-media.py: clean - all %d shipped file(s) reproduce '
          'byte for byte.' % len(targets))
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main(sys.argv))
    except Fatal as error:
        sys.stderr.write('FATAL: %s\n' % error)
        sys.stderr.write('This run has NO result, which is not a clean result '
                         '(I-029).\n')
        sys.exit(1)
