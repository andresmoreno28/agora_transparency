def field_value(entity, name):
    """The first `value` of a field, or None. Exports are always a list."""
    items = entity.get('default', {}).get(name)
    if not items:
        return None
    first = items[0]
    if not isinstance(first, dict):
        return None
    return first.get('value')


def field_entity(entity, name):
    """The uuid the first item of a field references, or None."""
    items = entity.get('default', {}).get(name)
    if not items:
        return None
    first = items[0]
    if not isinstance(first, dict):
        return None
    return first.get('entity')


def read_dir(kind):
    """Every export of one entity type, keyed by uuid."""
    directory = os.path.join(CONTENT, kind)
    if not os.path.isdir(directory):
        raise Fatal('%s/ does not exist - the scan has an empty scope' % directory)
    out = {}
    for name in sorted(os.listdir(directory)):
        if not name.endswith('.yml'):
            continue
        document = load_yaml(os.path.join(directory, name))
        meta = document.get('_meta') or {}
        uuid = meta.get('uuid')
        if not uuid:
            raise Fatal('%s/%s: no _meta.uuid' % (kind, name))
        # A repeated uuid would OVERWRITE the first entity silently, and the
        # count printed further down would still look right - one entity fewer
        # than there are files, with nothing saying which one went missing.
        if uuid in out:
            raise Fatal('%s/%s: uuid %s is already used by another export in '
                        'the same directory' % (kind, name, uuid))
        out[uuid] = document
    if not out:
        raise Fatal('%s/ enumerated 0 entities - the scan did not happen (I-028)'
                    % directory)
    return out


# ------------------------------------------------------------------- the pdf --

def esc(text):
    """PDF literal-string escaping, and the encoding the font declares."""
    out = text.replace('\\', r'\\').replace('(', r'\(').replace(')', r'\)')
    try:
        out.encode('cp1252')
    except UnicodeEncodeError as error:
        raise Fatal('character outside WinAnsiEncoding in: %s (%s)' % (text, error))
    return out


def lay_out(blocks):
    """Blocks of lines -> (size, y, text) operations, top down.

    A block is a list of already-wrapped lines. Lines inside a block step by
    LINE_STEP; the first line of each new block steps by BLOCK_STEP instead,
    which is the only thing that separates a heading from what it heads.
    """
    if not blocks or not blocks[0]:
        raise Fatal('a page with no title block')
    ops = [(TITLE_SIZE, TITLE_Y, blocks[0][0])]
    y = TITLE_Y - TITLE_GAP
    for block in blocks[1:]:
        if not block:
            continue
        for line in block:
            ops.append((BODY_SIZE, y, line))
            y -= LINE_STEP
        # Undo the step the last line took and take a block-sized one instead.
        y -= BLOCK_STEP - LINE_STEP
    return ops


def build_pdf(title, blocks):
    """The whole file, as bytes. Deterministic: no clock, no ids, no metadata."""
    ops = lay_out(blocks)
    # One text operation per line, and the stream ENDS with a newline that is
    # counted in /Length: `endstream` follows the content directly, with no
    # separator of its own. Getting that one byte wrong is the difference
    # between a file a reader accepts and a file it repairs silently.
    stream = ''.join(
        'BT /F1 %d Tf %d %d Td (%s) Tj ET\n' % (size, LEFT_MARGIN, y, esc(text))
        for size, y, text in ops
    )
    stream_bytes = stream.encode('cp1252')

    objects = [
        b'<</Type/Catalog/Pages 2 0 R>>',
        b'<</Type/Pages/Kids[3 0 R]/Count 1>>',
        ('<</Type/Page/Parent 2 0 R/MediaBox[0 0 %d %d]/Resources<</Font<</F1 '
         '4 0 R>>>>/Contents 5 0 R>>' % (PAGE_WIDTH, PAGE_HEIGHT)).encode('ascii'),
        b'<</Type/Font/Subtype/Type1/BaseFont/Helvetica/Encoding/WinAnsiEncoding>>',
        None,  # the content stream, assembled below
        ('<</Producer (%s)/Title (%s)>>' % (esc(PRODUCER), esc(title))).encode('cp1252'),
    ]

    out = bytearray(b'%PDF-1.4\n')
    offsets = []
    for number, body in enumerate(objects, 1):
        offsets.append(len(out))
        out += ('%d 0 obj\n' % number).encode('ascii')
        if number == 5:
            out += ('<</Length %d>>stream\n' % len(stream_bytes)).encode('ascii')
            out += stream_bytes
            out += b'endstream\n'
        else:
            out += body + b'\n'
        out += b'endobj\n'

    startxref = len(out)
    out += b'xref\n'
    out += ('0 %d\n' % (len(objects) + 1)).encode('ascii')
    out += b'0000000000 65535 f \n'
    for offset in offsets:
        out += ('%010d 00000 n \n' % offset).encode('ascii')
    out += b'trailer\n'
    out += ('<</Size %d/Root 1 0 R/Info %d 0 R>>\n'
            % (len(objects) + 1, len(objects))).encode('ascii')
    out += b'startxref\n'
    out += ('%d\n' % startxref).encode('ascii')
    out += b'%%EOF\n'
    return bytes(out)


def wrap(text, width):
    return textwrap.wrap(text, width=width,
                         break_long_words=False, break_on_hyphens=False)


def standing_blocks():
    """The two blocks every generated PDF ends with."""
    return [[DEMO_HEADING], wrap(DEMO_NOTE, PROSE_WIDTH), [LICENCE_NOTE]]


