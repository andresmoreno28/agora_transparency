class Fatal(Exception):
    """A condition under which this run has no result at all (I-029)."""


# --------------------------------------------------------------- yaml subset --

_KEY = re.compile(r'^( *)([A-Za-z0-9_.?-]+):(?: (.*))?$')
_SEQ = re.compile(r'^( *)-(?: (.*))?$')


def _scalar(raw, where):
    """The scalar spellings `drush site:export` actually emits, and no others."""
    if raw is None:
        return None
    text = raw.strip()
    if text == '' or text == 'null' or text == '~':
        return None
    if text == 'true':
        return True
    if text == 'false':
        return False
    if text.startswith("'"):
        if not text.endswith("'") or len(text) < 2:
            raise Fatal('%s: unterminated single-quoted scalar: %s' % (where, raw))
        return text[1:-1].replace("''", "'")
    if text.startswith('"'):
        if not text.endswith('"') or len(text) < 2:
            raise Fatal('%s: unterminated double-quoted scalar: %s' % (where, raw))
        body = text[1:-1]
        out = []
        i = 0
        while i < len(body):
            ch = body[i]
            if ch == '\\' and i + 1 < len(body):
                nxt = body[i + 1]
                out.append({'n': '\n', 't': '\t', '"': '"', '\\': '\\'}.get(nxt, nxt))
                i += 2
                continue
            out.append(ch)
            i += 1
        return ''.join(out)
    if re.match(r'^-?[0-9]+$', text):
        return int(text)
    # An unquoted scalar opening with a YAML indicator is a flow collection, an
    # anchor, an alias, a tag or a block scalar - none of which this reader
    # models. Refused rather than returned as a string, because returning
    # "{b: 1}" as text is a SILENT mis-parse, and a silent mis-parse is worse
    # than a crash in a script whose whole job is byte equality. Falsified
    # against all seven shapes on 2026-08-27.
    if text[0] in '{[&*!%@|>`':
        raise Fatal('%s: YAML this reader does not model: %s' % (where, raw))
    return text


def load_yaml(path):
    """Parse one exported entity file. Raises on anything outside the subset."""
    with open(path, 'r', encoding='utf-8', newline='') as handle:
        raw = handle.read()
    if '\r' in raw:
        raise Fatal('%s: carriage return in an exported entity file' % path)
    lines = [line for line in raw.split('\n')]
    # Drop the trailing empty element produced by the final newline, and any
    # blank line: the exporter emits none, and one appearing would mean the file
    # has been hand-edited into a shape this reader does not model.
    tokens = []
    for number, line in enumerate(lines, 1):
        if line.strip() == '':
            continue
        tokens.append((number, line))

    pos = [0]

    def peek():
        return tokens[pos[0]] if pos[0] < len(tokens) else None

    def indent_of(line):
        return len(line) - len(line.lstrip(' '))

    def parse_node(indent):
        token = peek()
        if token is None:
            raise Fatal('%s: unexpected end of file' % path)
        number, line = token
        if _SEQ.match(line):
            return parse_seq(indent)
        return parse_map(indent)

    def parse_map(indent):
        out = {}
        while True:
            token = peek()
            if token is None:
                return out
            number, line = token
            if indent_of(line) < indent:
                return out
            if indent_of(line) > indent:
                raise Fatal('%s:%d: unexpected indentation' % (path, number))
            match = _KEY.match(line)
            if not match:
                raise Fatal('%s:%d: not a mapping entry: %s' % (path, number, line))
            pos[0] += 1
            key, value = match.group(2), match.group(3)
            if value is None or value.strip() == '':
                nxt = peek()
                if nxt is not None and indent_of(nxt[1]) > indent:
                    out[key] = parse_node(indent_of(nxt[1]))
                elif nxt is not None and _SEQ.match(nxt[1]) and indent_of(nxt[1]) == indent:
                    out[key] = parse_seq(indent)
                else:
                    out[key] = None
            elif value.strip() == '{  }' or value.strip() == '{}':
                out[key] = {}
            else:
                out[key] = _scalar(value, '%s:%d' % (path, number))

    def parse_seq(indent):
        out = []
        while True:
            token = peek()
            if token is None:
                return out
            number, line = token
            if indent_of(line) != indent:
                return out
            match = _SEQ.match(line)
            if not match:
                return out
            pos[0] += 1
            inline = match.group(2)
            if inline is not None and inline.strip() != '':
                out.append(_scalar(inline, '%s:%d' % (path, number)))
                continue
            nxt = peek()
            if nxt is not None and indent_of(nxt[1]) > indent:
                out.append(parse_node(indent_of(nxt[1])))
            else:
                out.append(None)

    document = parse_map(0)
    if pos[0] != len(tokens):
        number, line = tokens[pos[0]]
        raise Fatal('%s:%d: trailing content this reader does not model: %s'
                    % (path, number, line))
    return document


